package vjezbe1;

import java.util.Scanner;

public class PrviZadatakSaKolokvijumaPrimjer {

	public static void main(String[] args) {
		int n;
		Scanner u = new Scanner(System.in);

		System.out.print("Unesi N: ");
		n = u.nextInt();

		while (n <= n) {
			System.out.print("Unesi N ponovo. N je <0");
		}

		for (int i = 1; i <= n; i++) {
			for (int j = 1; j <= 1; j++)
				System.out.print("*");
			System.out.print("\n");
		}

	}

}